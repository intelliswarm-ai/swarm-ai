package ai.intelliswarm.swarmai.memory;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.JdbcTemplate;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Objects;
import java.util.concurrent.atomic.AtomicLong;

/**
 * JDBC-backed implementation of the Memory interface.
 * Works with PostgreSQL, MySQL/MariaDB, and H2 — the DDL and inserts adapt to the
 * detected database (BIGSERIAL/JSONB are PostgreSQL-only; other databases get an
 * identity/auto-increment id and a TEXT metadata column).
 *
 * Search uses OR keyword semantics: the query is tokenized (see {@link MemoryKeywords}),
 * candidates matching ANY keyword are fetched newest-first, and results are ranked
 * client-side by number of keywords matched, then recency.
 *
 * <p>Retention: when {@code maxEntries} is positive, every {@value #TRIM_EVERY_N_SAVES}
 * saves the oldest rows beyond the cap are deleted, so the table cannot grow unbounded.
 *
 * Managed table (created automatically unless autoCreateTable=false):
 *   swarmai_memory(id, agent_id, content, metadata, created_at)
 *   with indexes on agent_id and created_at DESC.
 *
 * Configuration via application.yml:
 *   swarmai.memory.provider: jdbc
 *   spring.datasource.url: jdbc:postgresql://localhost:5432/swarmai
 *   spring.datasource.username: swarmai
 *   spring.datasource.password: swarmai_password
 */
public class JdbcMemory implements Memory {

    private static final Logger logger = LoggerFactory.getLogger(JdbcMemory.class);
    private static final String TABLE_NAME = "swarmai_memory";
    private static final ObjectMapper objectMapper = new ObjectMapper();

    /** Default row cap; 0 or negative disables retention trimming. */
    public static final int DEFAULT_MAX_ENTRIES = 100_000;
    /** Trim cost is amortized: retention runs once per this many saves. */
    private static final int TRIM_EVERY_N_SAVES = 200;

    private final JdbcTemplate jdbcTemplate;
    private final boolean autoCreateTable;
    private final boolean postgres;
    private final int maxEntries;
    private final AtomicLong saveCounter = new AtomicLong();

    /**
     * Creates JdbcMemory with automatic table creation.
     * For production, use Flyway migrations and set autoCreateTable=false.
     */
    public JdbcMemory(JdbcTemplate jdbcTemplate) {
        this(jdbcTemplate, true);
    }

    public JdbcMemory(JdbcTemplate jdbcTemplate, boolean autoCreateTable) {
        this(jdbcTemplate, autoCreateTable, DEFAULT_MAX_ENTRIES);
    }

    public JdbcMemory(JdbcTemplate jdbcTemplate, boolean autoCreateTable, int maxEntries) {
        this.jdbcTemplate = Objects.requireNonNull(jdbcTemplate, "JdbcTemplate cannot be null");
        this.autoCreateTable = autoCreateTable;
        this.maxEntries = maxEntries;
        this.postgres = detectPostgres();
        if (autoCreateTable) {
            initializeTable();
        }
        logger.info("JdbcMemory initialized (autoCreateTable={}, dialect={}, maxEntries={})",
                autoCreateTable, postgres ? "postgresql" : "generic", maxEntries);
    }

    private boolean detectPostgres() {
        try {
            String product = jdbcTemplate.execute(
                    (java.sql.Connection con) -> con.getMetaData().getDatabaseProductName());
            return product != null && product.toLowerCase(Locale.ROOT).contains("postgres");
        } catch (Exception e) {
            logger.warn("Could not detect database product, assuming generic SQL: {}", e.getMessage());
            return false;
        }
    }

    private void initializeTable() {
        String idColumn = postgres
                ? "id BIGSERIAL PRIMARY KEY"
                : "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
        String metadataColumn = postgres ? "metadata JSONB" : "metadata TEXT";

        jdbcTemplate.execute(
                "CREATE TABLE IF NOT EXISTS " + TABLE_NAME + " (" +
                idColumn + ", " +
                "agent_id VARCHAR(255), " +
                "content TEXT NOT NULL, " +
                metadataColumn + ", " +
                "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP" +
                ")");

        try {
            jdbcTemplate.execute(
                    "CREATE INDEX IF NOT EXISTS idx_swarmai_memory_agent ON " + TABLE_NAME + "(agent_id)");
            jdbcTemplate.execute(
                    "CREATE INDEX IF NOT EXISTS idx_swarmai_memory_created ON " + TABLE_NAME + "(created_at DESC)");
        } catch (Exception e) {
            logger.debug("Index creation skipped (may already exist): {}", e.getMessage());
        }
    }

    @Override
    public void save(String agentId, String content, Map<String, Object> metadata) {
        String metadataJson = null;
        if (metadata != null && !metadata.isEmpty()) {
            try {
                metadataJson = objectMapper.writeValueAsString(metadata);
            } catch (JsonProcessingException e) {
                logger.warn("Failed to serialize metadata as JSON, storing as null: {}", e.getMessage());
            }
        }

        String metadataPlaceholder = postgres ? "?::jsonb" : "?";
        jdbcTemplate.update(
                "INSERT INTO " + TABLE_NAME + " (agent_id, content, metadata, created_at) VALUES (?, ?, "
                        + metadataPlaceholder + ", ?)",
                agentId, content, metadataJson, Timestamp.from(Instant.now()));

        if (maxEntries > 0 && saveCounter.incrementAndGet() % TRIM_EVERY_N_SAVES == 0) {
            trimToCap();
        }

        logger.debug("Saved memory for agent {}: {} chars", agentId, content.length());
    }

    /** Deletes rows older than the newest {@code maxEntries} (id order ≈ insertion order). */
    private void trimToCap() {
        try {
            List<Long> boundary = jdbcTemplate.queryForList(
                    "SELECT id FROM " + TABLE_NAME + " ORDER BY id DESC LIMIT 1 OFFSET " + maxEntries,
                    Long.class);
            if (!boundary.isEmpty()) {
                int deleted = jdbcTemplate.update(
                        "DELETE FROM " + TABLE_NAME + " WHERE id <= ?", boundary.get(0));
                logger.debug("Memory retention trim removed {} rows beyond cap of {}", deleted, maxEntries);
            }
        } catch (Exception e) {
            logger.warn("Memory retention trim failed (will retry later): {}", e.getMessage());
        }
    }

    @Override
    public List<String> search(String query, int limit) {
        return searchScoped(query, null, limit);
    }

    @Override
    public List<String> searchByAgentPrefix(String query, String agentPrefix, int limit) {
        if (agentPrefix == null || agentPrefix.isEmpty()) {
            return search(query, limit);
        }
        return searchScoped(query, agentPrefix, limit);
    }

    /**
     * Matches rows containing ANY query keyword and ranks them by how many DISTINCT keywords each
     * row contains, then by recency.
     *
     * <p>The ranking is done in SQL, not client-side. An earlier version fetched the newest N
     * candidates and scored them in Java — but that truncates by recency BEFORE scoring, so a
     * strongly-matching older row can never be seen. With {@code limit=1}, five recent rows
     * containing only "database" would crowd out an older row containing
     * "database migration rollback", and the search would return the weaker match. Scoring in the
     * database means the ranking sees every matching row.
     *
     * <p>The score is a portable {@code SUM(CASE WHEN ... THEN 1 ELSE 0 END)} — no dialect-specific
     * full-text syntax — so it works on PostgreSQL, MySQL and H2 alike.
     */
    private List<String> searchScoped(String query, String agentPrefix, int limit) {
        if (query == null || query.isBlank() || limit <= 0) {
            return Collections.emptyList();
        }

        List<String> keywords = MemoryKeywords.tokenize(query);

        // Fall back to raw substring matching when the query yields no usable keywords.
        if (keywords.isEmpty()) {
            List<Object> params = new ArrayList<>();
            StringBuilder sql = new StringBuilder("SELECT content FROM " + TABLE_NAME + " WHERE ");
            if (agentPrefix != null) {
                sql.append("agent_id LIKE ?").append(LIKE_ESCAPE).append(" AND ");
                params.add(escapeLike(agentPrefix) + "%");
            }
            sql.append("LOWER(content) LIKE ?").append(LIKE_ESCAPE)
                    .append(" ORDER BY created_at DESC LIMIT ?");
            params.add("%" + escapeLike(query.toLowerCase(Locale.ROOT)) + "%");
            params.add(limit);
            return jdbcTemplate.queryForList(sql.toString(), String.class, params.toArray());
        }

        // score = how many distinct keywords the row contains
        StringBuilder score = new StringBuilder();
        List<Object> scoreParams = new ArrayList<>(keywords.size());
        for (int i = 0; i < keywords.size(); i++) {
            if (i > 0) {
                score.append(" + ");
            }
            score.append("(CASE WHEN LOWER(content) LIKE ?").append(LIKE_ESCAPE)
                    .append(" THEN 1 ELSE 0 END)");
            scoreParams.add("%" + escapeLike(keywords.get(i)) + "%");
        }

        String sql = "SELECT content FROM " + TABLE_NAME
                + " WHERE " + (agentPrefix != null ? "agent_id LIKE ?" + LIKE_ESCAPE + " AND " : "")
                + "(" + score + ") > 0"
                + " ORDER BY (" + score + ") DESC, created_at DESC LIMIT ?";

        // Placeholders bind in source order: [agent_id?] [WHERE score] [ORDER BY score] [limit].
        List<Object> params = new ArrayList<>();
        if (agentPrefix != null) {
            params.add(escapeLike(agentPrefix) + "%");
        }
        params.addAll(scoreParams);
        params.addAll(scoreParams);
        params.add(limit);

        return jdbcTemplate.queryForList(sql, String.class, params.toArray());
    }

    /**
     * The explicit {@code ESCAPE} clause for every LIKE built from {@link #escapeLike}. PostgreSQL
     * and MySQL default the LIKE escape to backslash, but H2 and SQLite have NO default escape
     * character — so without this clause the backslashes {@code escapeLike} adds are treated as
     * literal characters and the wildcard escaping silently does nothing. Declaring it makes the
     * escaping work identically on every supported database.
     */
    private static final String LIKE_ESCAPE = " ESCAPE '\\'";

    /** Escapes LIKE wildcards in user-derived text so they match literally. Pair with {@link #LIKE_ESCAPE}. */
    private static String escapeLike(String text) {
        return text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_");
    }

    @Override
    public List<String> getRecentMemories(String agentId, int limit) {
        if (agentId != null) {
            return jdbcTemplate.queryForList(
                    "SELECT content FROM " + TABLE_NAME +
                    " WHERE agent_id = ? ORDER BY created_at DESC LIMIT ?",
                    String.class, agentId, limit);
        } else {
            return jdbcTemplate.queryForList(
                    "SELECT content FROM " + TABLE_NAME +
                    " ORDER BY created_at DESC LIMIT ?",
                    String.class, limit);
        }
    }

    @Override
    public void clear() {
        jdbcTemplate.update("DELETE FROM " + TABLE_NAME);
        logger.info("JDBC memory cleared");
    }

    @Override
    public void clearForAgent(String agentId) {
        if (agentId != null) {
            jdbcTemplate.update("DELETE FROM " + TABLE_NAME + " WHERE agent_id = ?", agentId);
            logger.info("JDBC memory cleared for agent {}", agentId);
        }
    }

    @Override
    public int size() {
        Integer count = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM " + TABLE_NAME, Integer.class);
        return count != null ? count : 0;
    }

    @Override
    public boolean isEmpty() {
        return size() == 0;
    }
}
